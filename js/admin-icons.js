// Remplit tous les éléments [data-ico="nom"] (taille optionnelle : data-size)
export function remplirIcones(racine) {
  (racine || document).querySelectorAll("[data-ico]").forEach(function (n) {
    n.innerHTML = svg(n.dataset.ico, parseInt(n.dataset.size, 10) || 20);
  });
}
